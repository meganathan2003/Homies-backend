import { Schema, model, type HydratedDocument, type InferSchemaType } from "mongoose";

export const USER_ROLES = ['member', 'expert', 'admin'] as const;
export const USER_STATUSES = ['active', 'suspended'] as const;
export type UserRole = (typeof USER_ROLES)[number];


/**
 * Members fill the full onboarding (dob, mobile, work details...).
 * Experts/admins are created by an admin, so those fields are only required for members.
 * (`function` instead of an arrow: Mongoose calls it with `this` = the document.)
 */

/** Experts and admins must have a real name; members never store one. */


function requiredForMember(this: { role?: string }): boolean {
    return this.role === 'member';
}

function requiredForStaff(this: { role?: string }): boolean {
    return this.role !== 'member';
}

const userSchema = new Schema(
    {
        email: { type: String, required: true, unique: true, lowercase: true, trim: true },
        // sparse = many staff documents may have no uid yet; the unique index only applies when it exists.
        firebaseUid: { type: String, required: requiredForMember, unique: true, sparse: true },
        role: { type: String, enum: USER_ROLES, default: 'member' },
        status: { type: String, enum: USER_STATUSES, default: 'active' },

        // ---- public-facing identity (always generated by the server, never taken from the client) ----
        homiesId: { type: String, required: true, unique: true },
        // anonymousAlias: { type: String, required: true, unique: true },

        // ---- private profile (never shown to other users) ----
        name: { type: String, required: requiredForStaff, trim: true },
        dob: { type: Date, required: requiredForMember, select: false },
        mobileNumber: { type: String, required: requiredForMember, select: false },
        country: { type: String, required: requiredForMember, trim: true },
        state: { type: String, required: requiredForMember, trim: true },
        city: { type: String, required: requiredForMember, trim: true },
        profession: { type: String, required: requiredForMember, trim: true },
        typeOfWork: { type: String, required: requiredForMember, trim: true },
        workTiming: { type: String, required: requiredForMember, trim: true },
        // ---- onboarding state ----
        helps: { type: [String], default: [] },
        interests: { type: [String], default: [] },
        isImageVerified: { type: Boolean, default: false },
        isVoiceVerified: { type: Boolean, default: false },
        isProfileVerified: { type: Boolean, default: false },

        // ---- expert only ----
        expertProfile: {
            bio: { type: String, trim: true },
            specialization: { type: String, trim: true },
        },

        lastSeenAt: { type: Date },
    },
    { timestamps: true },

);
// Privacy rule: a member never has a stored name, even if some code path tries to set one.
userSchema.pre('validate', function () {
    if (this.role === 'member') this.name = undefined;
});
userSchema.index({ role: 1, status: 1 });

export type User = InferSchemaType<typeof userSchema>;
export type UserDoc = HydratedDocument<User>;
export const UserModel = model('User', userSchema);
